using System;
using System.Collections;
using System.Collections.Generic;
using UnityEngine;

public class FX_AttackEffect : MonoBehaviour
{
    #region========================================( Variables )======================================================//
    /*-----[ Inspector Variables ]------------------------------------------------------------------------------------*/
    public string effectName;
    public float destroyAfter;


    /*-----[ External Variables ]-------------------------------------------------------------------------------------*/


    /*-----[ Internal Variables ]-------------------------------------------------------------------------------------*/


    /*-----[ Reference Variables ]------------------------------------------------------------------------------------*/
    public Animator animator;


    #endregion


    #region=======================================( Functions )======================================================= //

    /*-----[ Mono Functions ]-----------------------------------------------------------------------------------------*/


    /*-----[ Internal Functions ]-------------------------------------------------------------------------------------*/
    public void Start()
    {
        if (animator != null)
        {
            animator.Play(effectName);
        }
        Destroy(gameObject, destroyAfter);
    }

    public void Update()
    {
    }


    /*-----[ External Functions ]-------------------------------------------------------------------------------------*/


    #endregion
}
